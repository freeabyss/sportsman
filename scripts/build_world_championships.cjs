function parsePair(s) {
  if (!s || s.includes('未设')) return null;
  let t = s.replace(/[（(][^）)]*[）)]/g, '').replace(/\s+/g, ' ').trim();
  // split on 、 or ， or , or space between two players sometimes joined
  let players = t.split(/[、，,]/).map(x => x.trim()).filter(Boolean);
  // some entries like "F.弗拉姆（奥地利） Z.梅什洛维茨..." have a space → also split on space if no 、
  if (players.length === 1 && players[0].includes(' ')) {
    // heuristic: split into two by last space if looks like two names
    const parts = players[0].split(' ');
    if (parts.length === 2) players = parts;
  }
  return players.length ? players : null;
}

function splitTeam(s) {
  if (!s || s === '-') return [];
  return s.split('、').map(x => x.trim()).filter(Boolean);
}

// 仅设单项(无团体)的年份举办地 —— 用于补齐赛事记录
const LOCATION_BY_YEAR = {
  1999:'荷兰埃因霍温', 2003:'法国巴黎', 2005:'中国上海', 2007:'克罗地亚萨格勒布',
  2009:'日本横滨', 2011:'荷兰鹿特丹', 2013:'法国巴黎', 2015:'中国苏州',
  2017:'德国杜塞尔多夫', 2019:'匈牙利布达佩斯', 2021:'美国休斯顿',
  2023:'南非德班', 2025:'卡塔尔多哈'
};

// build maps by year
const teamByYear = Object.fromEntries(TEAM.map(t => [t[0], t]));
const msByYear = Object.fromEntries(MS.map(t => [t[0], t]));
const wsByYear = Object.fromEntries(WS.map(t => [t[0], t]));
const dblByYear = Object.fromEntries(DBL.map(t => [t[0], t]));

const allYears = new Set([...TEAM.map(t=>t[0]), ...MS.map(t=>t[0]), ...WS.map(t=>t[0]), ...DBL.map(t=>t[0])]);
const newTournaments = [];
const newEvents = [];

const sortedYears = [...allYears].sort((a,b)=>a-b);
const yearToEdition = Object.fromEntries(sortedYears.map((y,i)=>[y, i+1]));

for (const year of sortedYears) {
  const t = teamByYear[year];
  const location = t ? t[1] : LOCATION_BY_YEAR[year];
  const mt = t ? t[2] : null;
  const wt = t ? t[3] : null;
  const editionNum = yearToEdition[year];
  const tid = `${year}-world-championships`;

  // preserve existing dates if present
  const existing = tournaments.find(x => x.id === tid);
  newTournaments.push({
    id: tid,
    name: `${year}年世界乒乓球锦标赛`,
    type: 'world_championships',
    level: 'S',
    year,
    start_date: existing ? existing.start_date : null,
    end_date: existing ? existing.end_date : null,
    location,
    edition: `第${editionNum}届`,
    participant_count: existing ? existing.participant_count : null
  });

  function addEvent(code, results) {
    if (!results || !results.length) return;
    newEvents.push({
      id: `${tid}-${CODE_SUFFIX[code]}`,
      tournament_id: tid,
      name: NAME[code],
      code,
      weight: WEIGHT[code],
      results
    });
  }

  // 男子单打
  if (msByYear[year]) {
    const [, c, r, t1, t2] = msByYear[year];
    addEvent('MEN_SINGLES', [
      { athlete_id: aid(c), rank: 1, medal: 'gold' },
      { athlete_id: aid(r), rank: 2, medal: 'silver' },
      { athlete_id: aid(t1), rank: 3, medal: 'bronze' },
      { athlete_id: aid(t2), rank: 3, medal: 'bronze' }
    ]);
  }
  // 女子单打
  if (wsByYear[year]) {
    const [, c, r, t1, t2] = wsByYear[year];
    addEvent('WOMEN_SINGLES', [
      { athlete_id: aid(c), rank: 1, medal: 'gold' },
      { athlete_id: aid(r), rank: 2, medal: 'silver' },
      { athlete_id: aid(t1), rank: 3, medal: 'bronze' },
      { athlete_id: aid(t2), rank: 3, medal: 'bronze' }
    ]);
  }
  // 男子团体
  const mtPlayers = splitTeam(mt);
  addEvent('MEN_TEAM', mtPlayers.map(p => ({ athlete_id: aid(p), rank: 1, medal: 'gold' })));
  // 女子团体
  if (wt && wt !== '-') {
    const wtPlayers = splitTeam(wt);
    addEvent('WOMEN_TEAM', wtPlayers.map(p => ({ athlete_id: aid(p), rank: 1, medal: 'gold' })));
  }
  // 双打
  if (dblByYear[year]) {
    const [, md, wd, xd] = dblByYear[year];
    const mdP = parsePair(md); if (mdP) addEvent('MEN_DOUBLES', mdP.map(p => ({ athlete_id: aid(p), rank: 1, medal: 'gold' })));
    const wdP = parsePair(wd); if (wdP) addEvent('WOMEN_DOUBLES', wdP.map(p => ({ athlete_id: aid(p), rank: 1, medal: 'gold' })));
    const xdP = parsePair(xd); if (xdP) addEvent('MIXED_DOUBLES', xdP.map(p => ({ athlete_id: aid(p), rank: 1, medal: 'gold' })));
  }
}

